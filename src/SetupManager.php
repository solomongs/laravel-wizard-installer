<?php

namespace SolomonGbeta\LaravelWizard;

final class SetupManager
{
    public function prepare(Paths $paths, array $options = []): string
    {
        $store = new StateStore($paths);
        if ($store->installed()) throw new InstallerException('This site is already installed. Preparation will not reopen a completed installer.', 'installed');
        $existing = $store->read();
        if ($existing && !in_array($existing['phase'] ?? '', ['prepared', 'configured', 'failed', 'migrating', 'finalizing'], true)) {
            throw new InstallerException('Setup status cannot be recognized. Ask your developer to review it.', 'state_corrupt');
        }
        foreach ([$paths->private, $paths->private.'/sessions'] as $directory) {
            if (!is_dir($directory) && !mkdir($directory, 0700, true) && !is_dir($directory)) {
                throw new InstallerException('Cannot create the private setup directory. Check storage permissions.', 'permissions');
            }
            chmod($directory, 0700);
        }
        // Defence in depth; never substitute these rules for a correct public document root.
        AtomicFile::write($paths->private.'/.htaccess', "Require all denied\n");
        AtomicFile::write($paths->private.'/index.html', '');
        $ttl = max(1, min(168, (int) ($options['ttl'] ?? 72)));
        $configuration = $this->configuration($paths, $options);
        $token = bin2hex(random_bytes(24));
        $store->locked(function () use ($store, $paths, $configuration, $token, $ttl): void {
            if ($store->installed()) throw new InstallerException('This site is already installed.', 'installed');
            $state = $store->read();
            $entry = $paths->public.'/install.php';
            if (!is_dir($paths->public) || !is_writable($paths->public)) throw new InstallerException('Create a writable public folder first.', 'public_missing');
            if (is_file($entry) && !str_contains((string) file_get_contents($entry), 'SolomonGbeta Laravel Wizard entry')) {
                throw new InstallerException('public/install.php already belongs to your project. Move it deliberately before preparing this installer.', 'file_conflict');
            }
            $paths->clearConfigCache();
            $setup = [
                'token_hash' => hash('sha256', $token),
                'expires_at' => time() + $ttl * 3600,
                'prepared_at' => gmdate('c'),
                'generation' => bin2hex(random_bytes(16)),
                'options' => $configuration,
            ];
            $package = realpath(dirname(__DIR__));
            $relativeBase = $this->relative($paths->public, $paths->base);
            $relativeBootstrap = $this->relative($paths->public, $package.'/bootstrap.php');
            $code = "<?php\n// SolomonGbeta Laravel Wizard entry; generated by wizard:prepare.\n";
            $code .= "if (PHP_VERSION_ID < 80100) { http_response_code(503); exit('Choose PHP 8.1 or newer in your hosting panel. Your Laravel project may require a newer version.'); }\n";
            $code .= '$base = realpath(__DIR__.'.var_export('/'.$relativeBase, true).");\n";
            $code .= '$loader = __DIR__.'.var_export('/'.$relativeBootstrap, true).";\n";
            $code .= "if (!\$base || !is_file(\$loader)) { http_response_code(503); exit('Installer files are missing. Upload the full prepared application including vendor.'); }\n";
            $code .= "require \$loader;\n\\SolomonGbeta\\LaravelWizard\\WebWizard::serve(\$base, __DIR__);\n";
            AtomicFile::write($entry, $code, 0644);
            if (!$state) $store->write(['phase' => 'prepared', 'profile' => 'other', 'steps' => [], 'message' => 'Ready to check your hosting.']);
            // Activate the code only after the entry point and cache preparation succeeded.
            $store->write($setup, 'setup');
        });
        return $token;
    }

    private function configuration(Paths $paths, array $overrides): array
    {
        $options = require dirname(__DIR__).'/config/laravel-wizard.php';
        $file = $paths->base.'/config/laravel-wizard.php';
        if (is_file($file)) {
            $project = require $file;
            if (!is_array($project)) throw new InstallerException('config/laravel-wizard.php must return a literal array.', 'config');
            $options = array_replace($options, $project);
        }
        if (isset($overrides['brand'])) $options['brand'] = (string) $overrides['brand'];
        if (!empty($overrides['allow-http'])) $options['require_https'] = false;
        if (!is_string($options['brand']) || strlen($options['brand']) > 100) throw new InstallerException('Use a website name under 100 characters.', 'config');
        if (!is_string($options['success_path']) || !preg_match('#^/(?!/)[^\r\n\\\\]*$#D', $options['success_path'])) {
            throw new InstallerException('success_path must be a local path starting with one slash.', 'config');
        }
        if ($options['after_install'] !== null && !is_string($options['after_install'])) throw new InstallerException('after_install must name an AfterInstall class.', 'config');
        if (!is_array($options['required_extensions'])) throw new InstallerException('required_extensions must be an array.', 'config');
        return $options;
    }

    private function relative(string $from, string $to): string
    {
        $a = explode('/', trim(str_replace('\\', '/', $from), '/'));
        $b = explode('/', trim(str_replace('\\', '/', $to), '/'));
        while ($a && $b && $a[0] === $b[0]) { array_shift($a); array_shift($b); }
        return str_repeat('../', count($a)).implode('/', $b);
    }
}
